#!/usr/bin/env python3
"""Deterministically build the single-file runtime assets from readable sources.

frontend-src/js/*.js  (sorted by name) -> frontend/app.js
frontend-src/css/*.css (sorted by name) -> frontend/style.css

No minifier, bundler, npm or network: files are concatenated with a header and
per-file markers so a shipped app.js can be traced back to its source module.
`--check` exits non-zero if the committed runtime files differ from a fresh
build (prevents hand-patching the generated files).
"""
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / 'frontend-src'
OUT = ROOT / 'frontend'


def bundle(kind):
    files = sorted((SRC / kind).glob('*.' + kind))
    if not files:
        raise SystemExit('no %s sources' % kind)
    parts = []
    digest = hashlib.sha256()
    for f in files:
        text = f.read_text(encoding='utf-8')
        if '\r' in text:
            raise SystemExit('CRLF in ' + f.name)
        digest.update(f.name.encode() + b'\0' + text.encode())
        marker = '/* --- %s --- */\n' % f.name
        parts.append(marker + text.rstrip('\n') + '\n')
    header = ('/* SBOX WebUI %s bundle. GENERATED by tools/build_frontend.py from frontend-src/%s/. '
              'Do not edit; source digest %s */\n') % (kind.upper(), kind, digest.hexdigest()[:16])
    if kind == 'js':
        header += "'use strict';\nconst PRODUCT_VERSION="+json.dumps(json.loads((ROOT.parent/'VERSION.json').read_text())['version'])+";\n"
    return header + ''.join(parts)


def main():
    check = '--check' in sys.argv
    status = 0
    for kind, name in (('js', 'app.js'), ('css', 'style.css')):
        built = bundle(kind)
        target = OUT / name
        if check:
            if not target.is_file() or target.read_text(encoding='utf-8') != built:
                print('STALE generated asset: frontend/' + name, file=sys.stderr)
                status = 1
        else:
            target.write_text(built, encoding='utf-8')
            print('%s  frontend/%s' % (hashlib.sha256(built.encode()).hexdigest(), name))
    for source in sorted((SRC/'portal').glob('portal.*'))+sorted((SRC/'shared').glob('usage.*'))+sorted((SRC/'shared').glob('export-center.*')):
        target=OUT/source.name
        if check:
            if not target.exists() or target.read_bytes()!=source.read_bytes():print('STALE portal asset: '+source.name,file=sys.stderr);status=1
        else:target.write_bytes(source.read_bytes())
    sys.exit(status)


if __name__ == '__main__':
    main()
